<p>
  utility bundles everyday helper commands that do not belong to a specific
  feature. members can use them to look things up, format text, or get quick
  information without leaving discord.
</p>

<p>
  enable the utility feature on the features page and the commands become
  available right away. there is nothing else to configure.
</p>

<h2>what members see</h2>
<p>
  /help is the main entry point. it gives members a quick way to discover the
  commands currently available on the server without reading the whole guide
  like homework. merciful, really.
</p>
