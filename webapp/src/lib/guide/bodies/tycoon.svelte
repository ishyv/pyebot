<p>
  tycoon is an idle system: members charter automated production lines that keep
  working over time, even while they are away.
</p>

<p>
  each line runs through stages, an extractor, a refinery, and an assembler, that
  members upgrade to produce more. the output can be spent as currency or used as
  rpg materials.
</p>

<h2>what members do</h2>
<p>
  members open the tycoon dashboard, start a line, upgrade stages, and come back
  later to collect the output. it pairs well with economy and rpg because it
  gives slower, passive progress beside active commands.
</p>

<Callout variant="tip">
  use tycoon when you want long-tail progression without asking members to spam
  commands every few minutes.
</Callout>
