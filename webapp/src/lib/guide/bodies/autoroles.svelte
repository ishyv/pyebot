<p>
  autoroles assigns one or more roles to every new member the moment they join
  your server. you can use it for a default member role, a color role, or
  anything else you want everyone to start with.
</p>

<p>
  to use autoroles, enable the autoroles feature on the features page, then
  choose the roles you want assigned from the roles list. the bot will apply
  them automatically from that point on.
</p>
